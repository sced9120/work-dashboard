const OUTPUT = `# 출력
마크다운으로 쓴다. 맨 앞에 제목이나 인사 없이 첫 번째 ## 제목부터 시작한다. 문장은 짧게, 전체 2,500자 안팎.`

export function buildReviewSystem(grade: ReviewGrade): string {
  return [COMMON, grade === '3' ? UPPER : LOWER, OUTPUT].join('\n\n')
}

export function buildReviewUser(maskedText: string, grade: ReviewGrade, career: string): string {
  const info = [`- 학년: ${grade}학년`]
  if (career.trim()) info.push(`- 진로 희망: ${career.trim().replace(/\s+/g, ' ')}`)
  return `# 학생 정보\n${info.join('\n')}\n\n# 학생부\n${maskedText.trim()}`
}

/** 모델이 붙인 머리말 · 코드 울타리를 걷어 낸다 */
export function cleanReport(raw: string): string {
  let t = String(raw || '').trim()
  t = t.replace(/^```(?:markdown|md)?\s*\n/i, '').replace(/\n```\s*$/, '')
  const at = t.indexOf('## ')
  return (at > 0 && at < 200 ? t.slice(at) : t).trim()
}

