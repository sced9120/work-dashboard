/* ---------- 이름 가리기 보조 — 담임이 적은 이름 · 학생부 머리의 성명 ---------- */

/** 성명 칸 뒤에 이름이 아닌 말이 오는 경우 */
const NOT_NAME = new Set(['및', '기재', '란', '학번', '반', '번호', '생년월일', '성별', '주소', '학년', '학교', '담임', '보호자', '연락처'])

/**
 * 학생부 머리의 '성명 : ○○○' · '성 명 ○○○' · 표 칸('성명 | ○○○', 탭) 모양에서 이름을 찾는다(되는 데까지).
 * 이름은 한글 두 글자에서 네 글자. 이름이 아닌 말(및 · 기재 …)은 건너뛴다.
 */
export function findHeaderNames(text: string): string[] {
  const out: string[] = []
  const re = /성\s*명[\s:：|│┃	]*([가-힣]{2,4})(?![가-힣])/g
  let m: RegExpExecArray | null
  const t = String(text ?? '')
  while ((m = re.exec(t))) {
    const n = m[1]
    if (NOT_NAME.has(n) || out.includes(n)) continue
    out.push(n)
  }
  return out
}

/** 담임이 적은 이름 + 학생부 머리에서 찾은 이름 — 두 글자에서 다섯 글자 한글 이름만, 겹치지 않게 */
export function extraMaskNames(text: string, typed: string): string[] {
  const out: string[] = []
  const t = String(typed ?? '').replace(/\s+/g, '')
  if (/^[가-힣]{2,5}$/.test(t)) out.push(t)
  for (const n of findHeaderNames(text)) if (!out.includes(n)) out.push(n)
  return out
}
