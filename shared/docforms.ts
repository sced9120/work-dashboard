/**
 * 학교에서 쓰는 문서의 서식.
 *
 * 문서마다 "무엇을 물어봐야 하는지(fields)" 와 "어떤 뼈대로 써야 하는지(outline)"
 * 를 여기 적어 둔다. 예시를 한 건도 넣지 않아도 이 뼈대만으로 문서가 나온다.
 *
 * 뼈대는 교육청 지침과 실제 학교 서식에서 공통으로 쓰이는 항목을 모은 것이다.
 * 예를 들어 회의록의 "일시·장소·참석자·안건·발언요지·결정사항" 은 학생생활교육
 * 위원회 운영 지침이 회의록에 반드시 남기라고 정한 항목이다.
 *
 * 학교마다 서식이 다르므로, 예시를 넣으면 **예시가 뼈대를 이긴다.**
 * (electron/main/ai.ts 의 docDraftPrompt 참고)
 */

export interface DocField {
  key: string
  label: string
  placeholder?: string
  hint?: string
  /** 여러 줄 칸의 높이(px). 없으면 한 줄짜리 */
  lines?: number
  required?: boolean
}

export interface DocForm {
  id: string
  /** 화면에서 묶어 보여 줄 갈래 */
  group: string
  icon: string
  name: string
  /** 한 줄 설명 */
  summary: string
  /** 기본 뼈대. 예시가 없으면 이 차례로 쓴다. */
  outline: string[]
  /** 문체와 지켜야 할 것 */
  guide: string
  fields: DocField[]
  /** 학생·보호자 실명이 들어가는 문서인가 — 가명처리 칸을 펼쳐 준다 */
  personal?: boolean
  /** 이 서식의 근거. 화면 아래에 작게 보여 준다. */
  basis?: string
}

