// PDF 변환 (electron/main/convert.ts) — 빌드된 앱의 IPC 로. 사진 · PDF 만 쓴다(한글 · 오피스는 부르지 않는다).
const path = require('path')
const fs = require('fs')
const { PDFDocument } = require(path.join(__dirname, '../node_modules/pdf-lib'))
const { handlers, next, USER_DATA, calls } = global.__it

let fails = 0
const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fails++ }
const call = (ch, ...args) => handlers.get(ch)({}, ...args)
const pages = async (f) => (await PDFDocument.load(fs.readFileSync(f))).getPageCount()
const makePdf = async (f, n) => {
  const d = await PDFDocument.create()
  for (let i = 0; i < n; i++) d.addPage([200, 200])
  fs.writeFileSync(f, await d.save())
}
const PNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAIAAAABCAIAAAB7QOjdAAAAD0lEQVR4nGP4z8DAwPAfAAcCAf9PcHyiAAAAAElFTkSuQmCC', 'base64')
const snapshot = (dir) => fs.readdirSync(dir, { recursive: true }).sort().map((n) => { const s = fs.statSync(path.join(dir, n)); return `${n}:${s.isFile() ? s.size : 'd'}` }).join('|')
const os = require('os')
const temps = () => fs.readdirSync(os.tmpdir()).filter((n) => n.startsWith('wd-convert-')).length

;(async () => {
  require(path.join(__dirname, '../out/main/index.js'))
  for (let i = 0; i < 100 && !handlers.has('convert:run'); i++) await new Promise((r) => setTimeout(r, 50))
  const tempBefore = temps()
  const dir = path.join(USER_DATA, '제출물')
  fs.mkdirSync(path.join(dir, '추가'), { recursive: true })
  await makePdf(path.join(dir, '10101(홍길동)_글.pdf'), 3)
  fs.writeFileSync(path.join(dir, '10101(홍길동)_사진.png'), PNG)
  await makePdf(path.join(dir, '10102 김철수.pdf'), 2)
  await makePdf(path.join(dir, '추가', '10102 김철수.pdf'), 1)
  fs.writeFileSync(path.join(dir, '10103(이영희).jpg'), 'not a photo')
  fs.writeFileSync(path.join(dir, '안내.zip'), 'x')
  fs.writeFileSync(path.join(dir, '~$임시.docx'), 'x')
  const original = snapshot(dir)

  console.log('1. 폴더 고르기')
  next.open.push([dir])
  const list = await call('convert:pickFolder')
  ok(list.ok && list.files.length === 5, `담은 파일 5개 (${list.files.length})`)
  ok(list.skipped.join() === '안내.zip', '못 바꾸는 형식은 알리고 임시 파일은 조용히')
  ok(!JSON.stringify(list).includes(USER_DATA), '경로는 화면에 넘기지 않음')
  ok((await call('convert:pickFiles')) === null, '고르기 취소')

  console.log('\n2. 파일마다 하나씩')
  const ids = list.files.map((f) => f.id)
  calls.sent.length = 0
  let r = await call('convert:run', { job: 'a', ids, options: { merge: 'none', excelFit: true } })
  const out = path.join(USER_DATA, '제출물_PDF')
  ok(r.ok && r.made === 4 && r.failed === 1 && r.folder === '제출물_PDF', `만든 4 · 실패 1 (${r.made} · ${r.failed})`)
  ok(fs.readdirSync(out).length === 4 && fs.existsSync(path.join(out, '10102 김철수 (2).pdf')), '같은 이름은 (2)')
  ok((await pages(path.join(out, '10101(홍길동)_사진.pdf'))) === 1, '사진은 한 쪽')
  const bad = calls.sent.find((c) => c.ch === 'convert:progress' && c.payload.status === 'error')
  ok(bad && /사진/.test(bad.payload.error), `실패 까닭: ${bad && bad.payload.error}`)
  ok(snapshot(dir) === original, '원본은 그대로')
  calls.opened.length = 0
  ok((await call('convert:reveal', 'a')) === true && calls.opened[0] === out, '저장한 폴더 열기')
  ok((await call('convert:reveal', USER_DATA)) === false, '모르는 값으로는 아무 폴더도 안 엶')

  console.log('\n3. 학생별 · 모두 하나로 (덮어쓰지 않음)')
  r = await call('convert:run', { job: 'b', ids, options: { merge: 'student' } })
  const out2 = path.join(USER_DATA, '제출물_PDF (2)')
  ok(r.ok && r.folder === '제출물_PDF (2)' && r.made === 2, `새 폴더에 2개 (${r.folder} · ${r.made})`)
  ok((await pages(path.join(out2, '10101(홍길동).pdf'))) === 4, '글 3쪽 + 사진 1쪽')
  ok((await pages(path.join(out2, '10102(김철수).pdf'))) === 3, '하위 폴더의 같은 학생도 합침')
  ok(r.failed === 1 && !fs.existsSync(path.join(out2, '10103(이영희).pdf')), '읽지 못한 것만 있는 학생은 파일을 만들지 않음')
  fs.writeFileSync(path.join(dir, '10101(홍길동)_사진2.jpg'), 'broken')
  next.open.push([dir])
  const again = await call('convert:pickFolder')
  r = await call('convert:run', { job: 'c', ids: again.files.map((f) => f.id), options: { merge: 'student' } })
  ok(r.notes.some((n) => /일부 빠짐/.test(n)) && fs.existsSync(path.join(USER_DATA, r.folder, '10101(홍길동) (일부 빠짐).pdf')), '빠진 파일이 있으면 이름에 남김')
  r = await call('convert:run', { job: 'd', ids: ids.slice(0, 3), options: { merge: 'all' } })
  const all = fs.readdirSync(path.join(USER_DATA, r.folder))
  ok(r.ok && all.length === 1 && /^제출물 전체/.test(all[0]), `하나로: ${all.join()}`)

  console.log('\n4. 파일 고르기 · 막는 것')
  next.open.push([path.join(dir, '10102 김철수.pdf')])
  const one = await call('convert:pickFiles')
  r = await call('convert:run', { job: 'e', ids: one.files.map((f) => f.id), options: {} })
  ok(r.ok && r.folder === 'PDF 변환' && fs.existsSync(path.join(dir, 'PDF 변환', '10102 김철수.pdf')), '파일을 고르면 옆의 PDF 변환 폴더')
  r = await call('convert:run', { job: 'f', ids: [path.join(dir, '10102 김철수.pdf')], options: {} })
  ok(!r.ok && /다시 골라/.test(r.error), '고르지 않은 경로는 읽지 않음')
  const empty = await call('convert:add', [path.join(dir, '안내.zip')])
  ok(!empty.ok && empty.files.length === 0, '바꿀 것이 없으면 알림')
  const both = await Promise.all([1, 2].map((n) => call('convert:run', { job: `g${n}`, ids, options: {} })))
  ok(both.filter((x) => /아직 끝나지/.test(x.error || '')).length <= 1, '겹쳐 돌리지 않음')

  console.log('\n5. 나누기')
  const five = path.join(USER_DATA, '묶음.pdf')
  await makePdf(five, 5)
  next.open.push([five])
  const s = await call('convert:pickSplit')
  ok(s.ok && s.pages === 5 && !JSON.stringify(s).includes(USER_DATA), '쪽수 · 경로 없음')
  r = await call('convert:split', s.id, '1-2, 4-')
  const cut = path.join(USER_DATA, '묶음_나눔')
  ok(r.ok && r.made === 2 && (await pages(path.join(cut, '묶음_1-2쪽.pdf'))) === 2 && (await pages(path.join(cut, '묶음_4-5쪽.pdf'))) === 2, '범위마다 파일')
  r = await call('convert:split', s.id, '9')
  ok(!r.ok && /벗어/.test(r.error) && !fs.existsSync(`${cut} (2)`), '틀린 범위면 폴더도 안 만듦')
  ok(!(await call('convert:addSplit', path.join(dir, '10103(이영희).jpg'))).ok, 'PDF 가 아니면 거절')
  ok(!(await call('convert:split', five, '1')).ok, '고르지 않은 경로는 나누지 않음')

  ok(temps() <= tempBefore, '임시 사본 폴더가 남지 않음')
  console.log(fails ? `\n실패 ${fails}` : '\n모두 통과')
  process.exit(fails ? 1 : 0)
})()
