// 상담 기록 — 빌드된 앱의 IPC 로: 저장 · 불러오기 · 지우기 · 상담 예정(달력 일정) · 인수인계 파일 제외 · 백업에는 포함 (가짜 자료만)
const path = require('path')
const fs = require('fs')
const { handlers, next, USER_DATA } = global.__it
let fails = 0
const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fails++ }
const call = (ch, ...args) => handlers.get(ch)({}, ...args)

;(async () => {
  require(path.join(__dirname, '../out/main/index.js'))
  for (let i = 0; i < 100 && !handlers.has('counsel:load'); i++) await new Promise((r) => setTimeout(r, 50))

  console.log('1. 기록 저장 · 불러오기')
  const a = await call('counsel:save', { no: 1, name: '가나다', date: '2026-04-07', who: '학부모', how: '전화', topics: ['진로'], text: '라마바고 진학 상담 비밀내용', follow: '다음 달 다시 통화' })
  ok(a.ok && a.record.id && a.record.how === '전화', '저장')
  const bad = await call('counsel:save', { no: 1, name: '가나다', date: '2026-04-07', text: '' })
  ok(!bad.ok && bad.message, '빈 기록은 거절')
  await call('counsel:save', { no: 2, name: '라마바', date: '2027-02-10', topics: ['생활'], text: '내용' })
  let l = await call('counsel:load', 2026)
  ok(l.year === 2026 && l.records.length === 2 && l.years.includes(2026), '2027년 2월은 2026학년도')
  const fix = await call('counsel:save', { id: a.record.id, no: 1, name: '가나다', date: '2027-03-04', text: '고침 비밀내용' })
  l = await call('counsel:load', 2026)
  const l27 = await call('counsel:load', 2027)
  ok(l.records.length === 1 && l27.records.length === 1 && l27.records[0].id === a.record.id && fix.record.created === a.record.created, '날짜를 다음 학년도로 고치면 옮겨 감 (id · 만든 때 유지)')
  ok(l27.years[0] === 2027 && l27.years.includes(2026), '학년도 목록')

  console.log('\n2. 학부모 연락처 · 메모')
  const m = await call('counsel:meta', { no: 1, contact: '어머니 010-0000-0000', memo: '가나다 메모' })
  await call('counsel:meta', { teacher: '라마바' })
  l = await call('counsel:load', 2026)
  ok(m.students['1'].contact.includes('010') && l.meta.teacher === '라마바' && l.meta.students['1'].memo === '가나다 메모', '저장 · 담임 이름')

  console.log('\n3. 상담 예정 ↔ 달력 일정')
  const p = await call('counsel:plan', { no: 2, name: '라마바', date: '2026-11-20', time: '15:30', who: '학생', memo: '고민 들어 주기' })
  ok(p.ok && p.plan.eventId, '예정 저장')
  let ev = (await call('events:list')).find((e) => e.id === p.plan.eventId)
  ok(ev && ev.title === '상담 — 2번' && ev.event_date === '2026-11-20' && ev.start_time === '15:30' && !JSON.stringify(ev).includes('라마바'), '달력 일정 만들어짐 (제목에 이름 없음)')
  const p2 = await call('counsel:plan', { id: p.plan.id, no: 2, name: '라마바', date: '2026-11-25', time: '', who: '학생' })
  ev = (await call('events:list')).find((e) => e.id === p.plan.eventId)
  ok(p2.plan.eventId === p.plan.eventId && ev.event_date === '2026-11-25' && (await call('events:list')).filter((e) => e.title === '상담 — 2번').length === 1, '예정을 고치면 일정도 고침 (새로 만들지 않음)')
  ok(await call('counsel:planCancel', p.plan.id), '취소')
  ok(!(await call('events:list')).some((e) => e.id === p.plan.eventId) && (await call('counsel:load', 2026)).plans.length === 0, '일정도 지워짐')
  const p3 = await call('counsel:plan', { no: 3, name: '가나다', date: '2026-12-01' })
  const done = await call('counsel:save', { no: 3, name: '가나다', date: '2026-12-01', text: '했음' }, p3.plan.id)
  ok(done.ok && !(await call('events:list')).some((e) => e.id === p3.plan.eventId) && (await call('counsel:load', 2026)).plans.length === 0, '완료로 기록하면 예정 · 일정이 사라짐')
  const p4 = await call('counsel:plan', { no: 4, name: '가나다', date: '2026-12-03' })
  await call('events:delete', p4.plan.eventId)
  ok((await call('counsel:load', 2026)).plans[0].eventId === undefined, '달력에서 먼저 지우면 예정은 남고 연결만 끊김')
  await call('counsel:planCancel', p4.plan.id)

  console.log('\n4. 인수인계 파일에는 없고 백업에는 있다')
  const out = path.join(USER_DATA, 'h.db')
  next.save.push(out)
  ok((await call('data:export', false)).ok, '인수인계 내보내기')
  const bytes = fs.readFileSync(out).toString('utf8')
  ok(!bytes.includes('비밀내용') && !bytes.includes('010-0000-0000') && !bytes.includes('counsel_'), '상담 내용 · 연락처 · 키가 파일에 없음')
  ok((await call('backup:now')).ok, '지금 백업')
  const dir = path.join(USER_DATA, 'backups')
  const bname = fs.readdirSync(dir).find((f) => f.startsWith('직접_'))
  const bb = bname ? fs.readFileSync(path.join(dir, bname)).toString('utf8') : ''
  ok(bb.includes('고침 비밀내용') && bb.includes('counsel_2027'), '이 PC 의 백업에는 들어 있음')

  console.log('\n5. 지우기')
  ok(await call('counsel:delete', a.record.id) && (await call('counsel:load', 2027)).records.length === 0, '지움')
  ok(!(await call('counsel:delete', 'nope')), '없는 기록')

  console.log(fails ? `\n실패 ${fails}` : '\n모두 통과')
  process.exit(fails ? 1 : 0)
})().catch((e) => { console.error('✗', e); process.exit(1) })
