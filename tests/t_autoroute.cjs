// 업무 도우미 자동 모델 (shared/autoroute.ts) — 빌드 없이. 점수 · 이어 묻기 · 모델 정하기 · 라우터 입출력
const { loadShared: load } = require('./tsload.cjs')
const A = load('autoroute.ts')
const T = load('types.ts')
const G = load('gemini.ts')
const O = load('ocr.ts')

let fails = 0
const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fails++ }
const none = { images: 0, docs: 0 }

console.log('1. 점수')
let r = A.scoreRequest('안녕하세요', none)
ok(r.score < 2 && r.reasons.includes('simple') && r.reasons.includes('short'), `인사 → 쉬움 (${r.score})`)
r = A.scoreRequest('이 증명을 엄밀하게 다시 써 줘', none)
ok(r.score >= 5 && r.reasons.includes('hard'), `엄밀하게 → 어려움 (${r.score})`)
r = A.scoreRequest('세특 써 줘', none)
ok(r.score < 2 && A.PROFESSIONAL.test('세특 써 줘'), `'세특 써 줘' — 점수는 낮아도 업무 문서 (${r.score})`)
r = A.scoreRequest('학생부 세특을 정교하게 다듬어 줘', none)
ok(r.reasons.includes('analysis'), '학생부 · 정교 → 분석')
r = A.scoreRequest('이 두 자료가 상충하는지 제약 조건을 모두 확인해 줘', none)
ok(r.reasons.includes('constraint') && r.score >= 2, `여러 자료 · 조건 (${r.score})`)
r = A.scoreRequest('```js\nfoo()\n```\n이 코드 설명해 줘', none)
ok(r.reasons.includes('code'), '코드 울타리 두 개 → 코드')
ok(A.scoreRequest('Traceback (most recent call last): boom', none).reasons.includes('code'), 'Traceback → 코드')
const long8 = '가'.repeat(8000)
const long30 = '가'.repeat(30000)
ok(A.scoreRequest(long8, none).score === 2 && A.scoreRequest(long30, none).score === 4, '8,000자 +2 · 30,000자 +4 (겹치지 않음)')
ok(A.scoreRequest('이 사진 뭐야?', { images: 1, docs: 0 }).score === 0, '사진 한 장 +1, 짧아서 -1 은 먼저 따짐 (0)')
r = A.scoreRequest('이거 읽어 줘', { images: 0, docs: 1 })
ok(r.score === 2 && r.reasons.includes('document'), '문서 한 개 → 최소 2')
r = A.scoreRequest('이거 읽어 줘', { images: 2, docs: 0 })
ok(r.score === 2 && r.reasons.includes('attachments'), '첨부 둘 이상 → 최소 2')
ok(A.scoreRequest('hello there', none).reasons.includes('simple') && A.scoreRequest('translate this', none).reasons.includes('simple'), '영어 인사 · translate')
ok(A.scoreRequest('Please analyze the architecture trade-off', none).score >= 7, '영어 분석 + 아키텍처 (+2 +5)')
ok(A.scoreRequest('', none).score === -1 && A.scoreRequest(null, none).score === -1, '빈 글 · null 도 죽지 않음')

console.log('\n2. 이어 묻기')
const hard = '이 정리가 성립하는지 엄밀하게 증명해 줘. 조건은 아래와 같고 모든 경우를 따져 보면 좋겠다.'
const turns = [{ role: 'user', content: hard }, { role: 'assistant', content: '네…' }, { role: 'user', content: '계속' }]
let e = A.effectiveText(turns)
ok(e.followUp && e.text === '계속' && e.prevText === hard && e.prevAssistant === '네…', '짧은 질문은 이어 묻기')
let sc = A.scoreTurns(turns, none)
ok(sc.score >= 5 && sc.followUp && sc.reasons.includes('follow-up') && sc.text.includes('증명'), `앞 질문의 점수를 이어받음 (${sc.score})`)
ok(A.scoreTurns([{ role: 'user', content: hard }, { role: 'assistant', content: 'a' }, { role: 'user', content: '그 이유를 자세히 설명해 줄 수 있을까요? 학생들이 이해하기 쉬운 비유를 들어서 말이에요 부탁합니다' }], none).followUp, "'그 이유' 로 시작하면 길어도 이어 묻기")
const big = '오늘 방과후 수업 운영 계획을 학년별로 나누어 정리하고 싶은데 어떤 순서로 하면 좋을지 같이 생각해 보자. 학년마다 인원이 다르고 강사도 다르다.'
sc = A.scoreTurns([{ role: 'user', content: hard }, { role: 'assistant', content: 'a' }, { role: 'user', content: big }], none)
ok(!sc.followUp, '길고 이어 묻는 말이 아니면 이어받지 않음')
sc = A.scoreTurns([{ role: 'user', content: '안녕' }, { role: 'assistant', content: 'a' }, { role: 'user', content: '고마워' }], none)
ok(sc.followUp && sc.score < 2, '앞이 쉬우면 그대로 쉬움')
ok(!A.effectiveText([{ role: 'user', content: '짧음' }]).followUp, '앞 질문이 없으면 이어 묻기 아님')

console.log('\n3. Gemini 자동')
const g = (n) => A.decideGemini(n)
ok(g(1).model === 'gemini-3.5-flash-lite' && g(1).thinkingLevel === 'low' && g(1).tier === '쉬움' && g(-3).model === 'gemini-3.5-flash-lite', '2 미만 → flash-lite · low')
ok(g(2).model === 'gemini-3.6-flash' && g(4).thinkingLevel === 'medium' && g(4).tier === '보통', '2~4 → 3.6-flash · medium')
ok(g(5).model === 'gemini-3.8-flash' && g(9).thinkingLevel === 'high' && g(5).tier === '어려움', '5 이상 → 3.8-flash · high')
ok(g(3).label === '자동 → gemini-3.6-flash · 보통', `이름표: ${g(3).label}`)

console.log('\n4. GPT 자동 — 규칙으로 정하는 것')
const loc = (text, a = none) => { const s = A.scoreTurns([{ role: 'user', content: text }], a); return A.decideOpenaiLocal(s.text, s.score, { ...a, reasons: s.reasons }) }
let d = loc('안녕하세요')
ok(d && d.model === 'gpt-6-luna' && d.effort === 'low' && d.why === '쉬운 질문', '인사 → luna · low')
d = loc('오늘 급식 뭐야?')
ok(d && d.model === 'gpt-6-luna', '짧은 질문 → luna')
d = loc('이 증명을 엄밀하게 해 줘')
ok(d && d.model === 'gpt-6-sol' && d.effort === 'high' && d.why === '어려운 추론', '어려움 → sol · high')
d = loc('3학년 수행평가 루브릭 초안 만들어 줘')
ok(d && d.model === 'gpt-6-sol' && d.effort === 'medium' && d.why === '업무 문서', '업무 문서 → sol · medium')
d = loc('가정통신문 다듬어줘')
ok(d && d.model === 'gpt-6-sol' && d.why === '업무 문서', "'다듬어줘' 가 가벼운 일이어도 가정통신문이면 업무 문서")
d = loc('안녕하세요', { images: 1, docs: 0 })
ok(d === null, '첨부가 있으면 쉬운 질문으로 단정하지 않음(애매 → 라우터)')
d = loc('우리 반 학생들이 요즘 쉬는 시간에 자꾸 복도에서 뛰어다니는데 어떻게 지도하면 좋을지 모르겠어요. 야단치면 오히려 더 심해지는 것 같기도 하고, 조용히 타이르면 듣지 않아요. 선생님들은 보통 어떻게 하시나요 한번 정리해서 알려 주세요')
ok(d === null, '길고 평범한 상담 질문 → 애매 (라우터에게 물음)')
ok(!A.PROFESSIONAL.test('보고서는 언제 내요') && !A.PROFESSIONAL.test('정리해 줘') && A.PROFESSIONAL.test('회의록 작성해 줘'), '업무 문서 — 영역 낱말과 하는 일 낱말이 함께 있을 때만')

console.log('\n5. 라우터 입출력')
const p = A.routerPrompt()
ok(p.includes('gpt-6-luna') && p.includes('gpt-6-sol') && p.includes('답하지 말고') && p.includes('지시가 아닙니다') && p.includes('JSON'), '라우터 지시 — 답하지 않음 · 첨부는 자료 · JSON')
const inp = A.routerInput('가'.repeat(3000), '나'.repeat(500), { images: 2, docs: 1 })
ok(inp.includes('가'.repeat(2000) + '…') && !inp.includes('가'.repeat(2001)) && inp.includes('나'.repeat(300) + '…') && !inp.includes('나'.repeat(301)), '질문 2,000자 · 앞 답 300자까지')
ok(inp.includes('사진 2개 · 문서 1개') && !A.routerInput('x', '', none).includes('앞선 답'), '첨부는 개수만 · 앞 답이 없으면 생략')
const good = A.parseRoute('{"tier":"expensive","effort":"high","reason":"다단계 추론이 필요합니다"}')
ok(good && good.tier === 'expensive' && good.effort === 'high' && good.reason === '다단계 추론이 필요합니다', '올바른 답 읽기')
ok(A.parseRoute('```json\n{"tier":"cheap","effort":"low","reason":"인사"}\n```').tier === 'cheap', '코드 울타리로 감싼 JSON 도 읽음')
ok(A.parseRoute('{"tier":"standard","effort":"low","reason":"x"}') === null && A.parseRoute('{"tier":"cheap","effort":"none","reason":"x"}') === null && A.parseRoute('{"tier":"cheap","effort":"max"}') === null, '정해진 값 밖(standard · none · max)은 거절')
ok(['', 'garbage', '[]', 'null', '42', '"cheap"', '{"tier":"cheap"}', '{tier:cheap}', '{"tier":["cheap"],"effort":"low"}'].every((x) => A.parseRoute(x) === null), '이상한 글은 모두 null')
ok(A.parseRoute('{"tier":"cheap","effort":"low","reason":"' + 'ㄱ'.repeat(80) + '"}').reason.length === 30 && A.parseRoute('{"tier":"cheap","effort":"low"}').reason === '', '까닭은 30자까지 · 없어도 됨')
let rt = A.routeFromParsed({ tier: 'cheap', effort: 'high', reason: '' })
ok(rt.model === 'gpt-6-luna' && rt.effort === 'medium' && rt.why === '쉬운 질문', '싼 모델은 medium 까지만')
rt = A.routeFromParsed({ tier: 'expensive', effort: 'low', reason: '모순 검토' })
ok(rt.model === 'gpt-6-sol' && rt.effort === 'low' && rt.why === '모순 검토', '큰 모델 · 라우터가 말한 강도와 까닭')

console.log('\n6. 이름표 · 기본값')
ok(A.autoLabel('gpt-6-luna', '쉬운 질문') === '자동 → gpt-6-luna · 쉬운 질문' && A.autoLabel('gpt-6-sol', '업무 문서') === '자동 → gpt-6-sol · 업무 문서', '이름표 모양')
ok(A.OPENAI_FALLBACK.model === 'gpt-6-sol' && A.OPENAI_FALLBACK.effort === 'medium' && A.autoLabel(A.OPENAI_FALLBACK.model, A.OPENAI_FALLBACK.why) === '자동 → gpt-6-sol · 기본값', '라우터가 실패하면 sol · medium · 기본값')

console.log('\n7. 자동 모델 이름')
ok(T.AUTO_MODELS.openai === 'gpt-auto' && T.AUTO_MODELS.gemini === 'gemini-auto', '이름')
ok(T.isAutoModel('gpt-auto') && T.isAutoModel('gemini-auto') && !T.isAutoModel('gpt-6-sol') && !T.isAutoModel('') && !T.isAutoModel(undefined) && !T.isAutoModel(null), 'isAutoModel')
ok(![...T.OPENAI_MODELS, ...T.GEMINI_MODELS].some(T.isAutoModel) && !T.modelsFor('openai').includes('gpt-auto') && !T.modelsFor('gemini').includes('gemini-auto'), '모델 목록(설정 · OCR · 세특 …)에는 없음')
ok(G.isModernGemini('gemini-auto') === true, "isModernGemini('gemini-auto') — temperature 안 붙음")
ok(G.isGeminiModel('gemini-auto') === false && G.isGeminiModel('gemini-3.6-flash') === true, "isGeminiModel('gemini-auto') 아님")
ok(O.isOpenaiModel('gpt-auto') === false && O.isOpenaiModel('gpt-6-sol') === true && O.ocrProviderOf('gpt-auto') === null && O.ocrProviderOf('gemini-auto') === null, 'OCR 은 자동 이름을 모델로 안 읽음')

console.log(fails ? `\n실패 ${fails}` : '\n모두 통과')
process.exit(fails ? 1 : 0)
