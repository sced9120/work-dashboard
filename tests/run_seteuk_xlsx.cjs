// 세특 작성실 — 엑셀로 주고받기. 빌드된 앱의 IPC 로 (AI 는 쓰지 않는다). 이름은 지어낸 것
const path = require('path')
const fs = require('fs')
const ExcelJS = require(path.join(__dirname, '../node_modules/exceljs'))
const { handlers, next, USER_DATA } = global.__it

let fails = 0
const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fails++ }
const call = (ch, ...args) => handlers.get(ch)({}, ...args)
global.fetch = async (url) => { throw new Error('바깥으로 나가면 안 됨 ' + url) }

;(async () => {
  require(path.join(__dirname, '../out/main/index.js'))
  for (let i = 0; i < 100 && !handlers.has('seteuk:xlsxExport'); i++) await new Promise((r) => setTimeout(r, 50))

  console.log('1. 내보내기')
  await call('seteuk:acts', [])
  let r = await call('seteuk:xlsxExport')
  ok(!r.ok && /없습니다/.test(r.message), `빈 작성실: ${r.message}`)
  await call('seteuk:roster', 'subject', [{ id: '1-1', cls: '1', no: '1', name: '가나다', group: '미적분A반', hakbun: '10101' }, { id: '1-2', cls: '1', no: '2', name: '라마바' }])
  await call('seteuk:acts', [{ id: 'a1', name: '함수 탐구', rec: '과세특', subject: '공통수학2', desc: '그래프', bytes: 600, amount: '넉넉히' }])
  await call('seteuk:rows', 'a1', { '1-1': { note: '기울기를 비교함\n발표함', ai: '초안 글.', final: '다듬은 글.' } })
  await call('seteuk:sum', '과세특', { '1-1': { ai: '줄인 글.', final: '취합에서 고친 글.' } })
  const out = path.join(USER_DATA, '내보냄.xlsx')
  next.save.push(out)
  r = await call('seteuk:xlsxExport')
  ok(r.ok && fs.existsSync(out), '엑셀 파일로 저장')
  const wb = new ExcelJS.Workbook()
  await wb.xlsx.readFile(out)
  ok(wb.worksheets.map((w) => w.name).join(' | ') === '👤 학생명단 ▸교과 | 🗂 활동목록 | 함수 탐구 ▸입력 | 📦 취합 ▸과세특', `시트: ${wb.worksheets.map((w) => w.name).join(' | ')}`)
  const rs = wb.getWorksheet('👤 학생명단 ▸교과')
  ok(rs.getRow(2).values.slice(1).join('|') === '반|번호|이름|수업반|학번' && rs.getRow(3).getCell(4).value === '미적분A반' && String(rs.getRow(3).getCell(5).value) === '10101' && !rs.getRow(4).getCell(4).value, '명단 시트 — 수업반 · 학번 칸')
  const ws = wb.getWorksheet('함수 탐구 ▸입력')
  ok(ws.getRow(3).getCell(4).value === '관찰 메모' && ws.getRow(4).getCell(3).value === '가나다' && ws.getRow(4).getCell(4).value === '기울기를 비교함\n발표함' && ws.getRow(4).getCell(6).value === '다듬은 글.', '3행 머리글 · 4행부터 학생 · 줄바꿈 그대로')

  console.log('\n2. 내보낸 파일을 다시 가져오기')
  next.open.push([out])
  let pv = await call('seteuk:xlsxPick')
  ok(pv.ok && pv.file === '내보냄.xlsx' && pv.report.students === 2 && pv.report.acts === 1 && !JSON.stringify(pv).includes(USER_DATA), '파일 읽기 (경로는 화면에 안 넘김)')
  ok(pv.report.cells === 0 && pv.report.kept === 0 && pv.report.newStudents === 0 && pv.report.newActs.length === 0 && pv.report.mergedActs.join() === '함수 탐구', '같은 자료라 바뀌는 것이 없음')
  // 빈 작성실로 만들고(다른 PC 인 셈) 가져온다
  await call('seteuk:acts', [])
  await call('seteuk:roster', 'subject', [])
  await call('seteuk:sum', '과세특', { '1-1': { ai: '', final: null } })
  pv = await call('seteuk:xlsxPreview', pv.id, false)
  ok(pv.ok && pv.report.newStudents === 2 && pv.report.newActs.join() === '함수 탐구' && pv.report.cells >= 4, `빈 작성실에서 미리 보기: 새 학생 2 · 새 활동 1 · 채우는 칸 ${pv.report.cells}`)
  ok((await call('seteuk:load')).acts.length === 0, '미리 보기만으로는 아무것도 바뀌지 않음')
  const ap = await call('seteuk:xlsxApply', pv.id, false)
  let all = await call('seteuk:load')
  const act = all.acts[0]
  ok(all.rosters.subject[0].group === '미적분A반' && all.rosters.subject[0].hakbun === '10101' && !all.rosters.subject[1].group, '가져오면 수업반 · 학번이 살아 있음')
  ok(ap.ok && all.rosters.subject.length === 2 && all.rosters.club.length === 0 && act.name === '함수 탐구' && act.subject === '공통수학2' && act.bytes === 600 && act.amount === '넉넉히' && act.desc === '그래프', '합치기 — 명단 · 활동 설정')
  ok(all.rows[act.id]['1-1'].note === '기울기를 비교함\n발표함' && all.rows[act.id]['1-1'].ai === '초안 글.' && all.rows[act.id]['1-1'].final === '다듬은 글.', '관찰 기록 · AI 초안 · 최종본')
  const sums = await call('seteuk:sums')
  ok(sums.과세특['1-1'].final === '취합에서 고친 글.' && sums.과세특['1-1'].ai === '줄인 글.', '취합에서 다듬은 글 · 압축본')
  ok((await call('seteuk:xlsxApply', pv.id, false)).ok === false, '한 번 합친 번호로는 다시 못 함')

  console.log('\n3. 세특 시트를 내려받은 파일 가져오기')
  const sheetWb = new ExcelJS.Workbook()
  sheetWb.addWorksheet('🚀 시작하기').addRow(['안내'])
  const ro = sheetWb.addWorksheet('👤 학생명단')
  ro.addRows([['명단'], ['반', '번호', '이름', '성취수준'], [1, 1, '가나다', 'A'], [1, 2, '다른이름', ''], [1, 3, '사아자', '']])
  const al = sheetWb.addWorksheet('🗂 활동목록')
  al.addRows([['활동'], ['활동키', '활동명', '기록종류', '교과영역', '바이트 한도', '입력 항목', '활동 개요', '프롬프트 모드', '직접 작성 프롬프트', '입력 시트', '예시 시트', '분량 맞추기'], ['A1', '함수 탐구', '과세특', '수학', 600, '관찰 메모', '', '바로쓰기', '', '함수 탐구 ▸입력', '', ''], ['A2', '동아리 발표', '동아리', '공통', 900, '관찰 메모', '발표 준비', '바로쓰기', '', '동아리 발표 ▸입력', '', '메모만큼']])
  const s1 = sheetWb.addWorksheet('함수 탐구 ▸입력')
  s1.addRows([['안내'], [], ['반', '번호', '이름', '성취수준', '관찰 메모', '생성', '모델', 'AI 결과', '최종본', '바이트', '검증'], [1, 1, '가나다', 'A', '시트에서 적은 메모', false, '', '시트 초안.', '시트 최종본.', 21, '통과'], [1, 2, '다른이름', '', '이름이 다른 학생 메모', false, '', '', '', '', ''], [1, 3, '사아자', '', '새 학생 메모', true, '', { formula: 'A1', result: '수식 결과 초안.' }, { richText: [{ text: '굵은 ' }, { font: { bold: true }, text: '최종본.' }] }, '', '']])
  const s2 = sheetWb.addWorksheet('동아리 발표 ▸입력')
  s2.addRows([['안내'], [], ['반', '번호', '이름', '성취수준', '관찰 메모', '생성', '모델', 'AI 결과', '최종본', '바이트', '검증'], [1, 1, '가나다', '', '발표를 맡음', false, '', '', '', '', '']])
  const sheetPath = path.join(USER_DATA, '세특 시트.xlsx')
  await sheetWb.xlsx.writeFile(sheetPath)
  next.open.push([sheetPath])
  pv = await call('seteuk:xlsxPick')
  ok(pv.ok && pv.report.students === 4 && pv.report.acts === 2 && pv.report.newStudents === 2 && pv.report.newActs.join() === '동아리 발표' && pv.report.mergedActs.join() === '함수 탐구', '시트 파일 읽기 — 새 학생 · 새 활동 · 합치는 활동')
  ok(pv.report.mismatched.length === 1 && pv.report.mismatched[0].includes('라마바') && pv.report.kept === 3, `이름이 다른 학생 · 이미 글이 있는 칸 ${pv.report.kept}: ${pv.report.mismatched[0]}`)
  await call('seteuk:xlsxApply', pv.id, false)
  all = await call('seteuk:load')
  const fa = all.acts.find((a) => a.name === '함수 탐구')
  const da = all.acts.find((a) => a.name === '동아리 발표')
  ok(all.rows[fa.id]['1-1'].final === '다듬은 글.' && all.rows[fa.id]['1-1'].note.includes('기울기'), '이미 적은 글은 그대로')
  ok(all.rows[fa.id]['1-3'].note === '새 학생 메모' && all.rows[fa.id]['1-3'].ai === '수식 결과 초안.' && all.rows[fa.id]['1-3'].final === '굵은 최종본.', '새 학생의 글 — 수식 결과 · 글자 모양이 든 칸도 글로')
  ok(!all.rows[fa.id]['1-2'] && all.rosters.subject.find((s) => s.id === '1-2').name === '라마바', '이름이 다른 학생은 넣지 않고 명단도 그대로')
  ok(da && da.rec === '동아리' && da.bytes === 900 && da.amount === '메모만큼' && da.desc === '발표 준비' && all.rows[da.id]['1-1'].note === '발표를 맡음' && all.rosters.club.map((s) => s.name).join() === '가나다', '새 활동 — 영역 · 분량 · 개요 · 글 · 동아리 명단은 따로')
  next.open.push([sheetPath])
  pv = await call('seteuk:xlsxPick')
  pv = await call('seteuk:xlsxPreview', pv.id, true)
  await call('seteuk:xlsxApply', pv.id, true)
  all = await call('seteuk:load')
  ok(all.rows[fa.id]['1-1'].final === '시트 최종본.' && all.rows[fa.id]['1-1'].note === '시트에서 적은 메모', '덮어쓰기를 고르면 파일의 글로')

  console.log('\n4. 읽지 못하는 파일')
  const bad = path.join(USER_DATA, 'bad.xlsx')
  fs.writeFileSync(bad, 'xlsx 아님')
  next.open.push([bad])
  pv = await call('seteuk:xlsxPick')
  ok(pv.ok === false && /엑셀/.test(pv.error), `엑셀이 아닌 파일: ${pv.error}`)
  const other = new ExcelJS.Workbook()
  other.addWorksheet('성적').addRows([['이름', '점수'], ['가', 1]])
  const otherPath = path.join(USER_DATA, 'other.xlsx')
  await other.xlsx.writeFile(otherPath)
  next.open.push([otherPath])
  pv = await call('seteuk:xlsxPick')
  ok(pv.ok === false && /세특 자료/.test(pv.error), `세특 자료가 없는 엑셀: ${pv.error}`)
  ok((await call('seteuk:xlsxPick')) === null, '고르지 않고 닫음')

  console.log(fails ? `\n실패 ${fails}` : '\n모두 통과')
  process.exit(fails ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
